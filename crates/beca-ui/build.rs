use std::ffi::OsStr;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    generate_embedded_ui_bundle();
    slint_build::compile("ui/rust_bindings.slint").expect("Slint build failed");
}

fn collect_slint_files(dir: &Path, base: &Path, out: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(dir).expect("read ui directory") {
        let entry = entry.expect("read ui entry");
        let path = entry.path();
        if path.is_dir() {
            collect_slint_files(&path, base, out);
        } else if path.extension() == Some(OsStr::new("slint")) {
            out.push(path.strip_prefix(base).expect("strip ui prefix").to_path_buf());
        }
    }
}

fn generate_embedded_ui_bundle() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let ui_dir = Path::new(&manifest_dir).join("ui");

    let mut names: Vec<PathBuf> = Vec::new();
    collect_slint_files(&ui_dir, &ui_dir, &mut names);
    names.sort();

    let mut generated = String::from("// @generated by build.rs — do not edit\n");
    generated.push_str("pub static EMBEDDED_UI_FILES: &[(&str, &str)] = &[\n");
    for name in &names {
        let rel = name.to_string_lossy().replace('\\', "/");
        generated.push_str(&format!(
            "    ({rel:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/ui/{rel}\"))),\n"
        ));
    }
    generated.push_str("];\n");

    let dest = Path::new(&out_dir).join("ui_bundle.rs");
    fs::write(&dest, generated).expect("write ui_bundle.rs");

    println!("cargo:rerun-if-changed=ui");
    for name in &names {
        println!("cargo:rerun-if-changed=ui/{}", name.to_string_lossy());
    }
}
