use std::ffi::OsStr;
use std::fs;
use std::path::Path;

fn main() {
    generate_embedded_ui_bundle();
    slint_build::compile("ui/library.slint").expect("Slint build failed");
}

/// Generate a Rust file that embeds every `.slint` file under `ui/`.
///
/// This keeps `ui_loader::embedded_ui_files()` and the interpreter bundle in
/// sync with the source tree automatically (adding a new component no longer
/// requires editing a manual `include_str!` list).
fn generate_embedded_ui_bundle() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let ui_dir = Path::new(&manifest_dir).join("ui");

    let mut names: Vec<String> = fs::read_dir(&ui_dir)
        .expect("read ui directory")
        .filter_map(|entry| entry.ok())
        .filter(|entry| entry.path().extension() == Some(OsStr::new("slint")))
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .collect();
    names.sort();

    let mut generated = String::from("// @generated by build.rs — do not edit\n");
    generated.push_str("pub static EMBEDDED_UI_FILES: &[(&str, &str)] = &[\n");
    for name in &names {
        generated.push_str(&format!(
            "    ({name:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/ui/{name}\"))),\n"
        ));
    }
    generated.push_str("];\n");

    let dest = Path::new(&out_dir).join("ui_bundle.rs");
    fs::write(&dest, generated).expect("write ui_bundle.rs");

    println!("cargo:rerun-if-changed=ui");
    for name in &names {
        println!("cargo:rerun-if-changed=ui/{name}");
    }
}
